// Hand-drawn 16x16 item sprites for the vanilla modes (Lucky Pillars' loot
// first). Each template is pixel art in palette letters, recoloured per
// material; tile_art_vanilla.ts falls back to its procedural silhouettes for
// shapes not listed here.
//
// Legend: '.' clear · '1'-'6' the material ramp, dark to light (stretched
// over however many shades the palette has) · 'a'-'d' the wooden handle ramp
// · 'o' the dark outline colour for inner lines · any other letter comes from
// the template's own `x` colours. Every sprite gets the outer outline after.

export interface ItemTemplate {
  rows: string[];
  /** Template-only colours (fixed, not recoloured by the material). */
  x?: Record<string, number>;
  /** Skip the automatic outer outline (the art draws its own). */
  noOutline?: boolean;
}

const T = (rows: string[], x?: Record<string, number>, noOutline?: boolean): ItemTemplate => ({ rows, x, noOutline });

